canvas.addEventListener("mousedown", (e) => {
  const pos = getCanvasCoords(e.clientX, e.clientY);
  if (gameState === "SELECT" && hoveredCharacter) {
    selectHero(hoveredCharacter);
    return;
  }
  if (gameState === "PLAY") {
    if (pos.x >= questButton.x && pos.x <= questButton.x + questButton.w &&
        pos.y >= questButton.y && pos.y <= questButton.y + questButton.h) {
      isQuestOpen = !isQuestOpen;
      isInventoryOpen = false;
      return;
    }
    if (pos.x >= bagButton.x && pos.x <= bagButton.x + bagButton.w &&
        pos.y >= bagButton.y && pos.y <= bagButton.y + bagButton.h) {
      isInventoryOpen = !isInventoryOpen;
      isQuestOpen = false;
      return;
    }
    if (isQuestOpen) { handleQuestClick(pos.x, pos.y); return; }
    if (isInventoryOpen) { handleInventoryClick(pos.x, pos.y); return; }

    const distToJump = Math.hypot(pos.x - jumpBtn.x, pos.y - jumpBtn.y);
    if (distToJump <= jumpBtn.radius + 10) {
      triggerJump();
      return;
    }

    const distToJoy = Math.hypot(pos.x - joystick.baseX, pos.y - joystick.baseY);
    if (distToJoy <= joystick.radius + 30) {
      joystick.isMouseDragging = true;
      joystick.active = true;
      updateJoystickPosition(pos.x, pos.y);
    }
  }
});

window.addEventListener("mouseup", () => {
  if (joystick.isMouseDragging) {
    joystick.isMouseDragging = false;
    joystick.active = false;
    joystick.knobX = joystick.baseX;
    joystick.knobY = joystick.baseY;
    joystick.inputX = 0;
    joystick.inputY = 0;
  }
});

function updateJoystickPosition(touchX, touchY) {
  const dx = touchX - joystick.baseX;
  const dy = touchY - joystick.baseY;
  const dist = Math.hypot(dx, dy);

  if (dist <= joystick.radius) {
    joystick.knobX = touchX;
    joystick.knobY = touchY;
    joystick.inputX = dist === 0 ? 0 : dx / joystick.radius;
    joystick.inputY = dist === 0 ? 0 : dy / joystick.radius;
  } else {
    const angle = Math.atan2(dy, dx);
    joystick.knobX = joystick.baseX + Math.cos(angle) * joystick.radius;
    joystick.knobY = joystick.baseY + Math.sin(angle) * joystick.radius;
    joystick.inputX = Math.cos(angle);
    joystick.inputY = Math.sin(angle);
  }
}

