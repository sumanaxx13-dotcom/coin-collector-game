function getCanvasCoords(clientX, clientY) {
  const rect = canvas.getBoundingClientRect();
  return {
    x: (clientX - rect.left) * (canvas.width / rect.width),
    y: (clientY - rect.top) * (canvas.height / rect.height)
  };
}

function triggerJump() {
  if (isInventoryOpen || isQuestOpen) return;

  if (!player.isJumping) {
    player.vy = player.jumpForce;
    player.isJumping = true;
    player.canDoubleJump = true;
    player.isBackflipping = false;
    player.rotation = 0;
    player.totalJumps++;
    spawnCollectSparks(player.x, player.y, "#ffffff", 6);
  } else if (player.canDoubleJump) {
    player.vy = player.doubleJumpForce;
    player.canDoubleJump = false;
    player.isBackflipping = true;
    player.totalJumps++;
    spawnCollectSparks(player.x, player.y + player.jumpOffset, "#38bdf8", 14);
  }
}

// Keyboard Listeners
window.addEventListener("keydown", (e) => {
  keys[e.key] = true;

  if (gameState === "SELECT") {
    if (e.key === "1") selectHero("GIRL");
    if (e.key === "2") selectHero("BOY");
  } else if (gameState === "PLAY") {
    if (e.key === "e" || e.key === "E") {
      if (!isQuestOpen) isInventoryOpen = !isInventoryOpen;
      return;
    }

    if (e.key === "q" || e.key === "Q" || e.key === "?") {
      if (!isInventoryOpen) isQuestOpen = !isQuestOpen;
      return;
    }

    if (isInventoryOpen) {
      const idx = parseInt(e.key) - 1;
      const available = getAvailableShopItems();
      if (idx >= 0 && idx < available.length) {
        buyItemByReference(available[idx]);
      }
      return;
    }

    if (e.key === " ") {
      triggerJump();
    }
  }
});

window.addEventListener("keyup", (e) => {
  keys[e.key] = false;
});

