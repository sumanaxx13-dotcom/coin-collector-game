// 4. Main Update Loop
function update() {
  ambientTick++;
  if (shopNoticeTimer > 0) shopNoticeTimer--;

  if (questTransitionTimer > 0) {
    questTransitionTimer--;
    if (questTransitionTimer === 0) {
      advanceToNextQuestTier();
    }
  }

  if (gameState === "PLAY") {
    if (!isInventoryOpen && !isQuestOpen) {
      let dx = 0;
      let dy = 0;

      // 1. Keyboard
      if (keys["a"] || keys["A"] || keys["ArrowLeft"]) dx -= 1;
      if (keys["d"] || keys["D"] || keys["ArrowRight"]) dx += 1;
      if (keys["w"] || keys["W"] || keys["ArrowUp"]) dy -= 1;
      if (keys["s"] || keys["S"] || keys["ArrowDown"]) dy += 1;

      if (dx !== 0 && dy !== 0) {
        dx *= 0.7071;
        dy *= 0.7071;
      }

      // 2. Joystick
      if (joystick.active) {
        dx = joystick.inputX;
        dy = joystick.inputY;
      } else {
        if (dx !== 0 || dy !== 0) {
          joystick.knobX = joystick.baseX + dx * (joystick.radius * 0.75);
          joystick.knobY = joystick.baseY + dy * (joystick.radius * 0.75);
        } else {
          joystick.knobX = joystick.baseX;
          joystick.knobY = joystick.baseY;
        }
      }

      if (dx > 0.15) player.facing = "right";
      else if (dx < -0.15) player.facing = "left";

      player.movingSideways = Math.abs(dx) > 0.2;
      player.moving = Math.abs(dx) > 0.05 || Math.abs(dy) > 0.05;

      if (player.moving) {
        player.walkCycle += player.movingSideways ? 0.28 : 0.20;
      } else {
        player.walkCycle = 0;
      }

      player.x += dx * player.speed;
      player.y += dy * player.speed;

      // 3. Jump Physics
      if (player.isJumping) {
        player.jumpOffset += player.vy;
        player.vy += player.gravity;

        if (player.isBackflipping) {
          const flipDirection = player.facing === "right" ? -1 : 1;
          player.rotation += flipDirection * 0.32;

          if (Math.random() < 0.45) {
            spawnCollectSparks(player.x, player.y + player.jumpOffset, "#38bdf8", 1);
          }
        }

        if (player.jumpOffset >= 0) {
          player.jumpOffset = 0;
          player.vy = 0;
          player.isJumping = false;
          player.canDoubleJump = false;
          player.isBackflipping = false;
          player.rotation = 0;
        }
      }

      // Camera Tracking
      camera.x = player.x - canvas.width / 2;
      camera.y = player.y - canvas.height / 2;

      // Coins Loop
      coinSpawnTimer++;
      if (coinSpawnTimer > 35 && coins.length < 24) {
        coinSpawnTimer = 0;
        spawnInfiniteCoin();
      }

      coins.forEach(c => {
        const distFromPlayer = Math.hypot(c.x - player.x, c.y - player.y);
        if (distFromPlayer > 1000) {
          const angle = Math.random() * Math.PI * 2;
          const radius = 250 + Math.random() * 500;
          c.x = player.x + Math.cos(angle) * radius;
          c.y = player.y + Math.sin(angle) * radius;
        }
      });

      // Coin Collision
      const effectivePlayerY = player.y + player.jumpOffset;
      const playerHitboxRadius = 24;

      for (let i = coins.length - 1; i >= 0; i--) {
        const c = coins[i];
        c.wobble += 0.08;

        const dist = Math.hypot(player.x - c.x, effectivePlayerY - c.y);
        if (dist < playerHitboxRadius + c.radius) {
          score += 10;
          player.totalCoinsCollected++;
          spawnCollectSparks(c.x, c.y, "#facc15", 8);
          coins.splice(i, 1);
        }
      }
    }

    // Particle Decay
    for (let i = particles.length - 1; i >= 0; i--) {
      const p = particles[i];
      p.x += p.vx;
      p.y += p.vy;
      p.life--;
      if (p.life <= 0) particles.splice(i, 1);
    }
  }
}

