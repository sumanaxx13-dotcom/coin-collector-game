function handleQuestClick(mx, my) {
  const boxW = 620;
  const boxH = 410;
  const boxX = canvas.width / 2 - boxW / 2;
  const boxY = canvas.height / 2 - boxH / 2;

  if (mx >= boxX + boxW - 45 && mx <= boxX + boxW - 15 && my >= boxY + 16 && my <= boxY + 44) {
    isQuestOpen = false;
    return;
  }

  const startY = boxY + 80;
  const slotH = 72;

  activeQuests.forEach((q, idx) => {
    const itemY = startY + idx * slotH;
    const progress = Math.min(q.goal, q.current());
    const isCompleted = progress >= q.goal;

    if (isCompleted && !q.claimed) {
      if (mx >= boxX + boxW - 110 && mx <= boxX + boxW - 25 && my >= itemY + 18 && my <= itemY + 52) {
        q.claimed = true;
        score += q.reward;
        spawnCollectSparks(player.x, player.y, "#38bdf8", 18);
        shopNotice = `Claimed +${q.reward} Coins from ${q.title}!`;
        shopNoticeTimer = 75;

        const allCompleted = activeQuests.every(quest => quest.claimed);
        if (allCompleted) {
          questTransitionTimer = 75;
        }
      }
    }
  });
}

function buyItemByReference(item) {
  if (!item) return;

  if (score >= item.price) {
    score -= item.price;
    item.owned++;
    player.equippedItem = item;
    shopNotice = `Bought ${item.name}!`;
    shopNoticeTimer = 70;
  } else {
    shopNotice = "Not enough coins!";
    shopNoticeTimer = 70;
  }
}

function handleInventoryClick(mx, my) {
  const boxW = 820;
  const boxH = 460;
  const boxX = canvas.width / 2 - boxW / 2;
  const boxY = canvas.height / 2 - boxH / 2;

  if (mx >= boxX + boxW - 45 && mx <= boxX + boxW - 15 && my >= boxY + 16 && my <= boxY + 44) {
    isInventoryOpen = false;
    return;
  }

  const startY = boxY + 74;
  const slotW = 370;
  const slotH = 58;
  const currentStage = currentQuestTierIndex + 1;

  for (let i = 0; i < MASTER_SHOP_ITEMS.length; i++) {
    const item = MASTER_SHOP_ITEMS[i];
    const isUnlocked = item.unlockStage <= currentStage;

    const col = i % 2;
    const row = Math.floor(i / 2);
    const itemX = boxX + 22 + col * (slotW + 24);
    const itemY = startY + row * slotH;

    if (itemY + slotH > boxY + boxH) continue;

    if (isUnlocked) {
      // Buy Button Click
      if (mx >= itemX + slotW - 70 && mx <= itemX + slotW - 8 && my >= itemY + 11 && my <= itemY + 39) {
        buyItemByReference(item);
        return;
      }

      // Equip Item Click
      if (mx >= itemX && mx <= itemX + slotW - 75 && my >= itemY && my <= itemY + 50 && item.owned > 0) {
        player.equippedItem = item;
        shopNotice = `Holding ${item.name}!`;
        shopNoticeTimer = 70;
        return;
      }
    }
  }
}

